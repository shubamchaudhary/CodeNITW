// Builds the job finder's skill lists from your resumes, so the extension scores Naukri jobs
// against the same skills the radar uses. Run it again after changing a resume:
//
//   node extensions/naukri-refresher-dev/make-job-profile.mjs
//
// Reads the resume texts the radar caches (.radar/resume.txt = SDE, .radar/resume-2.txt =
// GenAI; it re-reads the PDFs first when pdftotext is available) and radar/skills.json, then
// writes two files into the extension (it can't import from outside its own folder):
//   job-profile.js   — { backend, ai, extra, want }: each resume's skills (the Backend filter
//                      checks jobs against the SDE resume, the AI filter against the GenAI one),
//                      plus the extras and "want" list from radar/skills.json, used by both
//   score-opening.js — an exact copy of scripts/scoreOpening.mjs (the radar's skill dictionary)
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadResumeTexts, resumePdfs, resumeProfile } from '../../scripts/radar/resume.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const STATE = join(ROOT, '.radar');
const EXT = join(ROOT, 'extensions/naukri-refresher');

function envPdfs() {
  const p = join(STATE, '.env');
  if (!existsSync(p)) return undefined;
  const m = readFileSync(p, 'utf8').match(/^\s*RESUME_PDF\s*=\s*(.+?)\s*$/m);
  return m ? m[1].replace(/^["']|["']$/g, '') : undefined;
}

const { texts } = loadResumeTexts({ stateDir: STATE, pdfPaths: resumePdfs(envPdfs()), log: () => {} });
if (texts.length < 2) throw new Error(`need both resumes (SDE and GenAI); found ${texts.length}. Run the radar once or check RESUME_PDF`);
const [backend, ai] = texts.map((t) => resumeProfile(t).skills);
const listed = JSON.parse(readFileSync(join(ROOT, 'radar/skills.json'), 'utf8'));
const extra = [...new Set(listed.have || [])];
const want = [...new Set(listed.want || [])]; // each filter drops the ones its own resume already has

const profile = { generated: new Date().toISOString().slice(0, 10), backend, ai, extra, want };
writeFileSync(join(EXT, 'job-profile.js'),
  '// Generated by naukri-refresher-dev/make-job-profile.mjs from your two resumes and radar/skills.json.\n'
  + '// Re-run that script after changing a resume; don\'t edit by hand.\n'
  + `export const JOB_PROFILE = ${JSON.stringify(profile, null, 2)};\n`);
copyFileSync(join(ROOT, 'scripts/scoreOpening.mjs'), join(EXT, 'score-opening.js'));
console.log(`job-profile.js: backend (SDE) ${backend.length}, ai (GenAI) ${ai.length}, extra ${extra.length}, want ${want.length} skills`);
