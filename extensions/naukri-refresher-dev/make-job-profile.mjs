// Builds the job finder's list of your skills: every skill the skills dictionary
// (extensions/naukri-refresher/skills-dict.js) finds in your two resumes, plus the extras listed
// in radar/skills.json, plus what they imply (Spring Boot → Spring, Java). Run it again after
// changing a resume:
//
//   node extensions/naukri-refresher-dev/make-job-profile.mjs
//
// Reads the resume texts the radar caches (.radar/resume.txt = SDE, .radar/resume-2.txt =
// GenAI; it re-reads the PDFs first when pdftotext is available) and writes job-profile.js into
// the extension (it can't import from outside its own folder).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadResumeTexts, resumePdfs } from '../../scripts/radar/resume.mjs';
import { findSkills, withParents, skillOf } from '../naukri-refresher/skills-dict.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const STATE = join(ROOT, '.radar');
const EXT = join(ROOT, 'extensions/naukri-refresher');

function envPdfs() {
  const p = join(STATE, '.env');
  if (!existsSync(p)) return undefined;
  const m = readFileSync(p, 'utf8').match(/^\s*RESUME_PDF\s*=\s*(.+?)\s*$/m);
  return m ? m[1].replace(/^["']|["']$/g, '') : undefined;
}

const { texts } = loadResumeTexts({ stateDir: STATE, pdfPaths: resumePdfs(envPdfs()), log: () => {} });
if (texts.length < 2) throw new Error(`need both resumes (SDE and GenAI); found ${texts.length}. Run the radar once or check RESUME_PDF`);
const counted = (labels) => labels.filter((l) => skillOf(l).count).sort((a, b) => a.localeCompare(b));
const [sde, genai] = texts.map((t) => counted([...findSkills(t, { keepParents: true }).keys()]));
const listed = JSON.parse(readFileSync(join(ROOT, 'radar/skills.json'), 'utf8'));
const extras = counted([...new Set((listed.have || []).flatMap((x) => [...findSkills(x, { keepParents: true }).keys()]))]);
const skills = counted([...withParents([...sde, ...genai, ...extras])]);

const profile = { generated: new Date().toISOString().slice(0, 10), skills, resumes: { sde, genai }, extras };
writeFileSync(join(EXT, 'job-profile.js'),
  '// Generated by naukri-refresher-dev/make-job-profile.mjs from your two resumes and radar/skills.json.\n'
  + '// Re-run that script after changing a resume; don\'t edit by hand.\n'
  + `export const JOB_PROFILE = ${JSON.stringify(profile, null, 2)};\n`);
const onlyExtras = extras.filter((l) => !sde.includes(l) && !genai.includes(l));
console.log(`job-profile.js: ${skills.length} skills (SDE resume ${sde.length}, GenAI resume ${genai.length}, from skills.json only: ${onlyExtras.join(', ') || 'none'})`);
